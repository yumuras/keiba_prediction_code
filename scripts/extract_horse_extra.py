_T = np.array([np.unpackbits(np.frombuffer(bytes.fromhex(h), np.uint8)).astype(bool) for _, h in GLYPHS])
_L = [c for c, _ in GLYPHS]
_FR = [i for i, c in enumerate(_L) if c in "½¼¾"]
_NUM = {"½": "1", "¼": "1", "¾": "3"}
_DEN = {"½": "2", "¼": "4", "¾": "4"}


def glyph_bits(page, c, height):
    """文字 c の部分だけを描いて、インクのある範囲を 24×24 の白黒にする"""
    w = page.get_width()
    img = page.render(scale=SCALE, crop=(c["x0"] - 0.3, height - c["bottom"] - 0.3,
                                         w - c["x1"] - 0.3, c["top"] - 0.3)).to_pil().convert("L")
    a = np.array(img) < 128
    # 表の横の罫線（端から端まで続く線）が重なっていたら除く（縦は㈱のかっこを消してしまうので除かない）
    if a.size and (a.mean(1) < 0.9).any():
        a = a[a.mean(1) < 0.9]
    ys, xs = np.where(a)
    if len(ys) == 0:
        return None
    a = a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    return np.array(Image.fromarray(a.astype(np.uint8) * 255).resize((24, 24))) > 100


def classify(bits, fraction):
    if bits is None:
        return "?"
    if fraction:  # 着差の欄の外字は分数だけ
        t = _T[_FR].reshape(-1, 24, 24)
        b = bits.reshape(24, 24)
        nd = (t[:, :12, :12] != b[:12, :12]).sum((1, 2))
        dd = (t[:, 12:, 12:] != b[12:, 12:]).sum((1, 2))
        num = _NUM[_L[_FR[int(nd.argmin())]]]
        den = _DEN[_L[_FR[int(dd.argmin())]]]
        return {("1", "2"): "½", ("1", "4"): "¼", ("3", "4"): "¾"}.get((num, den), "?")
    d = (_T != bits.ravel()).sum(1)
    j = int(d.argmin())
    return _L[j] if d[j] <= MAX_DIST else "?"


def lines_text(cs, resolve):
    """文字を行（上下の位置）ごとにまとめ、上の行から左→右の順につなぐ（2行に折り返した名前のため）"""
    cs = sorted(cs, key=lambda c: c["top"])
    lines = []
    for c in cs:
        if lines and c["top"] - lines[-1][-1]["top"] <= 2.2:
            lines[-1].append(c)
        else:
            lines.append([c])
    return "".join(resolve(c) for ln in lines for c in sorted(ln, key=lambda c: c["x0"]))


def one(path):
    doc = pdfium.PdfDocument(str(path))
    out = []
    with pdfplumber.open(path) as pdf:
        for pi, p in enumerate(pdf.pages):
            p = p.dedupe_chars(tolerance=1, extra_attrs=("size",))
            cache = {}

            def resolve(c, fraction=False):
                t = ct(c)
                if t != "?":
                    return t
                k = (c["fontname"], c["text"], fraction)
                if k not in cache:
                    cache[k] = classify(glyph_bits(doc[pi], c, p.height), fraction)
                return cache[k]

            for x0, x1 in HALVES:
                chars = [c for c in p.chars if x0 <= c["x0"] < min(x1, p.width)]
                if not chars:
                    continue
                off = detect_offset(chars, x0)
                rel = lambda c: c["x0"] - off  # noqa: E731
                text = fix_text(p.crop((x0, 0, min(x1, p.width), p.height)).extract_text() or "")
                heads = parse_headers(text)
                hys = header_ys(chars, off)[:len(heads)]
                bounds = list(zip(hys, hys[1:] + [1e9]))
                # 馬の行（extract_pdf.parse_pdf と同じ見つけ方）
                starts = [c for c in chars if 49 <= rel(c) < 50.5 and not ct(c).isdigit()]
                row_ys = []
                for s in sorted(starts, key=lambda c: c["top"]):
                    if any(20.5 <= rel(c) < 22 and ct(c).isdigit() and abs(c["top"] - s["top"]) < 2 for c in chars):
                        if not row_ys or abs(s["top"] - row_ys[-1]) > 2:
                            row_ys.append(s["top"])
                for h, (lo, hi) in zip(heads, bounds):
                    ys = [y for y in row_ys if lo < y < hi]
                    for k, y in enumerate(ys):
                        ny = ys[k + 1] if k + 1 < len(ys) else y + 9
                        # 行の範囲。前に付く㈱などは少し上にずれ、行の間隔が広いページでは次の行の名前が上にずれるので、3.5pt 上で区切る
                        band = [c for c in chars if y - 3.5 <= c["top"] < min(ny - 3.5, y + 9)]
                        rc = [c for c in chars if -5 < c["top"] - y < 5]
                        rowtxt = txt([c for c in rc if abs(c["top"] - y) < 2.5])
                        if "除外" in rowtxt or "取消" in rowtxt:
                            continue
                        r = parse_row(rc, y, off)
                        if not r["umaban"]:
                            continue
                        # 騎手の国（騎手名の下の小さい「（豪）」など）
                        cc = [c for c in chars if 150 <= rel(c) < 200 and 3.5 < c["top"] - y < 7.8 and c["size"] < 4.2]
                        m = re.search(r"（(.+?)）", txt(cc))
                        country = m.group(1) if m else ""
                        # 馬主（騎手の右、調教師の左。長い名前は2行）
                        oc = [c for c in band if 190.5 <= rel(c) < 235 and c not in cc]
                        owner = lines_text(oc, resolve).replace(" ", "")
                        # 生産者（産地の右。産地の欄に先頭がかかることがあるので、産地の後ろのカタカナも足す）
                        reg = txt([c for c in band if 262 <= rel(c) < 275.5 and -1.5 <= c["top"] - y < 3]).replace(" ", "")
                        lead = re.search(r"[ァ-ヴー]+$", reg)
                        # 生産者の欄は x≈301 まで。その右はブリンカーの「B」の欄（x≈304）
                        bc = [c for c in band if 275.5 <= rel(c) < 301.5]
                        breeder = ((lead.group(0) if lead else "") + lines_text(bc, resolve)).replace(" ", "")
                        # 着差
                        mc = [c for c in band if 354 <= rel(c) < 380 and -2.5 < c["top"] - y < 2.5]
                        mtxt = "".join(resolve(c, fraction=True) for c in sorted(mc, key=lambda c: c["x0"])).replace(" ", "")
                        mm = MARGIN_RE.fullmatch(mtxt)
                        out.append(dict(race_id=h["race_id"], umaban=int(r["umaban"]), horse_name=r["name"],
                                        owner=owner, breeder=breeder, margin=mm.group(0) if mm else "",
                                        jockey_country=country, _mraw=mtxt))
    return out


